-- タスクリスト用のテーブル・ビューを作成する
-- Supabase の SQL Editor で1回だけ実行してください。
--
-- 実行前に、既存の tasks テーブルの RLS ポリシーを確認し、
-- 下の "authenticated read/write" ポリシーの条件を同じ考え方に合わせてください。
--   select policyname, cmd, qual from pg_policies where tablename = 'tasks';

begin;

create table public.tasklist_issues (
  id bigint generated by default as identity primary key,
  project_number text not null,
  found_date date,
  finder text,
  owner text,
  machine text,
  unit text,
  category text,              -- '出荷前' '現地工事' '出荷後' など
  item text,                  -- 指摘内容
  design_owner text,
  construction_owner text,
  status text not null default '0 未着手',
  current_process_due date,
  due_date date,
  completed_date date,
  detail text,
  is_archived boolean not null default false,
  created_by text,
  updated_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.tasklist_issue_notes (
  id bigint generated by default as identity primary key,
  issue_id bigint not null references public.tasklist_issues(id) on delete cascade,
  noted_at date not null default current_date,
  body text not null,
  created_by text,
  created_at timestamptz not null default now()
);

create index on public.tasklist_issues (project_number);
create index on public.tasklist_issues (status);
create index on public.tasklist_issue_notes (issue_id);

comment on table public.tasklist_issues is '2000番台工事の外観検査以降の指摘事項・出荷後の不具合（旧 タスクリスト_各工番.xlsm）';
comment on table public.tasklist_issue_notes is 'tasklist_issues の「状況」欄の履歴（日付・担当者つきで追記）';

create or replace view public.assignee_directory as
select email, max(name) as name, max(department) as department
from (
  select email, name, department from public.profiles
  union all
  select email, name, department from public.notification_recipients
  union all
  select email, name, null as department from public.members
) u
where email is not null
group by email;

alter table public.tasklist_issues enable row level security;
alter table public.tasklist_issue_notes enable row level security;

create policy "authenticated read/write" on public.tasklist_issues
  for all using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');
create policy "authenticated read/write" on public.tasklist_issue_notes
  for all using (auth.role() = 'authenticated') with check (auth.role() = 'authenticated');

commit;
